"""Small trained classifier: MiniLM sentence embeddings + logistic regression.

Training text is generated by ``work/T05/make_train_text.py`` from templates we
wrote ourselves; no reference episode text is used.  The fitted three-headed
model is written by ``work/T05/train_embed.py`` and loaded here.

For ``support_gap`` the input to the encoder is the claim and the cited document
joined by a separator.  The classifier predicts support, and the feature is
``1 - P(support)``.  For the other two features the classifier predicts risk
directly.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

NAME = "embed_lr"
KIND = "text+pair"
DEVICE = "mps"

MODEL_ID = "sentence-transformers/all-MiniLM-L6-v2"
LICENCE = "Apache-2.0"


def _root() -> Path:
    return Path(__file__).resolve().parents[2]


def _cache() -> str:
    env = os.environ.get("OG_S1_HF_HOME")
    return os.path.abspath(env) if env else str(_root() / "data" / "models" / "hf")


def model_path() -> Path:
    env = os.environ.get("OG_S1_EMBED_MODEL")
    if env:
        return Path(env)
    return _root() / "work" / "T05" / "embed_lr.joblib"


def default_device() -> str:
    try:
        import torch

        if torch.backends.mps.is_available():
            return "mps"
        if torch.cuda.is_available():
            return "cuda"
    except Exception:
        pass
    return "cpu"


_ENCODER = None
_ENCODER_DEVICE: str | None = None
_BUNDLE: dict[str, Any] | None = None
_BUNDLE_MTIME: float | None = None


def _encoder(device: str | None = None):
    global _ENCODER, _ENCODER_DEVICE
    from sentence_transformers import SentenceTransformer

    want = device or default_device()
    if _ENCODER is None or _ENCODER_DEVICE != want:
        _ENCODER = SentenceTransformer(MODEL_ID, cache_folder=_cache(), device=want, local_files_only=True)
        _ENCODER_DEVICE = want
    return _ENCODER


def _bundle() -> dict[str, Any]:
    global _BUNDLE, _BUNDLE_MTIME
    import joblib

    path = model_path()
    if not path.exists():
        raise FileNotFoundError(
            f"{path} is missing; run work/T05/train_embed.py before scoring"
        )
    mtime = path.stat().st_mtime
    if _BUNDLE is None or _BUNDLE_MTIME != mtime:
        _BUNDLE = joblib.load(path)
        _BUNDLE_MTIME = mtime
    return _BUNDLE


def embed_texts(texts: list[str], device: str | None = None) -> "Any":
    import numpy as np

    enc = _encoder(device)
    arr = enc.encode(
        texts,
        batch_size=32,
        show_progress_bar=False,
        convert_to_numpy=True,
        normalize_embeddings=True,
    )
    return np.asarray(arr, dtype=float)


def pair_features(hypotheses: list[str], premises: list[str], device: str | None = None) -> "Any":
    """Symmetric pair representation: both embeddings, product and difference."""
    import numpy as np

    eh = embed_texts(hypotheses, device)
    ep = embed_texts(premises, device)
    return np.hstack([eh, ep, eh * ep, np.abs(eh - ep)])


def score(items: list[dict[str, Any]], device: str | None = None) -> "Any":
    import numpy as np

    bundle = _bundle()
    out = np.full(len(items), np.nan, dtype=float)

    text_pos = [i for i, it in enumerate(items) if it.get("feature") in ("hype", "authority_language")]
    pair_pos = [i for i, it in enumerate(items) if it.get("feature") == "support_gap"]

    if text_pos:
        texts = [str(items[i].get("text", "")) for i in text_pos]
        X = embed_texts(texts, device)
        hype = [i for i in text_pos if items[i].get("feature") == "hype"]
        auth = [i for i in text_pos if items[i].get("feature") == "authority_language"]
        if hype:
            idx = [text_pos.index(i) for i in hype]
            p = bundle["hype"].predict_proba(X[idx])[:, 1]
            for i, v in zip(hype, p):
                out[i] = float(v)
        if auth:
            idx = [text_pos.index(i) for i in auth]
            p = bundle["authority_language"].predict_proba(X[idx])[:, 1]
            for i, v in zip(auth, p):
                out[i] = float(v)

    if pair_pos:
        hypotheses = [str(items[i].get("hypothesis", "")) for i in pair_pos]
        premises = [str(items[i].get("premise", "")) for i in pair_pos]
        X = pair_features(hypotheses, premises, device)
        p = bundle["support_gap"].predict_proba(X)[:, 1]
        for i, v in zip(pair_pos, p):
            out[i] = float(1.0 - v)

    out = np.nan_to_num(out, nan=0.5)
    return np.clip(out, 0.0, 1.0)
