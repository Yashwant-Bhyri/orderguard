"""Audit reader-3 training text against the reference corpora.

Training text is generated by ``make_train_text.py`` without reading
``data/ref/``.  This independent check reads the reference text only to verify
that no 6-word sequence from a training row appears in any reference text.  A
non-zero overlap is a leakage finding and makes the run fail.

The check is deliberately literal: lowercase, keep alphanumerics and a few
numeric symbols, and compare contiguous 6-grams.  It reports the worst rows so
a failure is actionable without dumping the corpus.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
N = 6
_TOKEN = re.compile(r"[a-z0-9$%.\-]+")


def _grams(text: str, n: int = N) -> set[str]:
    words = _TOKEN.findall(str(text or "").lower())
    return {" ".join(words[i : i + n]) for i in range(len(words) - n + 1)}


def _ref_texts(data_dir: Path) -> list[str]:
    texts: list[str] = []
    for path in sorted(data_dir.glob("*.jsonl")):
        with path.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                episode = json.loads(line)
                for doc in episode.get("documents") or []:
                    texts.append(doc.get("text", ""))
                for note in episode.get("initial_notes") or []:
                    texts.append(note.get("text", ""))
                for step in episode.get("steps") or []:
                    action = step.get("action") or {}
                    if action.get("rationale"):
                        texts.append(action["rationale"])
                    for claim in action.get("claims") or []:
                        texts.append(claim.get("text", ""))
                    for note in (step.get("pre_notes") or []) + (step.get("new_notes") or []):
                        texts.append(note.get("text", ""))
    return texts


def _row_text(row: dict) -> str:
    if row.get("feature") == "support_gap":
        return f"{row.get('premise', '')} {row.get('hypothesis', '')}"
    return str(row.get("text", ""))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--train", default="work/T05/train_text/train_text.jsonl")
    parser.add_argument("--data-dir", default="data/ref")
    parser.add_argument("--out", default="work/T05/leakage.json")
    parser.add_argument("--max-overlaps", type=int, default=0)
    args = parser.parse_args(argv)

    ref_grams: set[str] = set()
    for text in _ref_texts(Path(args.data_dir)):
        ref_grams |= _grams(text)

    rows: list[dict] = []
    with Path(args.train).open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))

    overlaps = []
    by_feature: dict[str, int] = {}
    for row in rows:
        shared = _grams(_row_text(row)) & ref_grams
        if shared:
            by_feature[row["feature"]] = by_feature.get(row["feature"], 0) + 1
            overlaps.append(
                {
                    "feature": row["feature"],
                    "label": int(row.get("label", -1)),
                    "shared_6grams": sorted(shared)[:3],
                    "text": _row_text(row)[:240],
                }
            )

    report = {
        "n": N,
        "train_rows": len(rows),
        "ref_texts": len(_ref_texts(Path(args.data_dir))),
        "overlapping_rows": len(overlaps),
        "by_feature": by_feature,
        "examples": overlaps[:10],
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    print(
        f"training/ref {N}-gram audit: {len(overlaps)} overlapping rows of {len(rows)} "
        f"({by_feature or 'none'}); wrote {out}"
    )
    if len(overlaps) > args.max_overlaps:
        for item in overlaps[:5]:
            print(f"  {item['feature']}: {item['shared_6grams']} :: {item['text'][:120]}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
